  // PHONE SEARCH NORMALIZATION
  // ===========================================================

  String _normalizePhoneForSearch(
      String phone,
      ) {
    final String value =
    phone.trim();

    if (value.isEmpty) {
      return '';
    }

    final bool hasLeadingPlus =
    value.startsWith(
      '+',
    );

    final String digits =
    _digitsOnlyPhone(
      value,
    );

    if (digits.isEmpty) {
      return '';
    }

    return hasLeadingPlus
        ? '+$digits'
        : digits;
  }

  String? _normalizePhoneSearchQuery(
      String value,
      ) {
    final String trimmed =
    value.trim();

    if (trimmed.isEmpty ||
        !_phoneSearchCharacterPattern.hasMatch(
          trimmed,
        )) {
      return null;
    }

    final String normalized =
    _normalizePhoneForSearch(
      trimmed,
    );

    return normalized.isEmpty
        ? null
        : normalized;
  }

  String _digitsOnlyPhone(
      String phone,
      ) {
    return phone.replaceAll(
      RegExp(
        r'[^0-9]',
      ),
      '',
    );
  }

  List<String> _phoneSearchKeys(
      String phone,
      ) {
    final String trimmed =
    phone.trim();

    if (trimmed.isEmpty) {
      return const <String>[];
    }

    final Set<String> values =
    <String>{};

    final String normalized =
    _normalizePhoneForSearch(
      trimmed,
    );

    final String digits =
    _digitsOnlyPhone(
      trimmed,
    );

    if (normalized.isNotEmpty) {
      values.add(
        normalized,
      );
    }

    if (digits.isNotEmpty) {
      values.add(
        digits,
      );
    }

    if (trimmed.startsWith(
      '+',
    ) &&
        digits.isNotEmpty) {
      values.add(
        '+$digits',
      );
    }

    return List<String>.unmodifiable(
      values,
    );
  }

  bool _looksLikePhone(
      String value,
      ) {
    final String trimmed =
    value.trim();

    if (trimmed.isEmpty ||
        !_phoneSearchCharacterPattern.hasMatch(
          trimmed,
        )) {
      return false;
    }

    final String digits =
    _digitsOnlyPhone(
      trimmed,
    );

    return digits.length >= 6;
  }

