/// ===========================================================
/// JR CALL
/// File: firestore_service.dart
/// Location: lib/services/firebase/firestore_service.dart
///
/// OTP / AUTH / PROFILE / GLOBAL DISCOVERY MASTER
///
/// PURPOSE:
///
/// Canonical production Firestore repository for JR CALL users.
///
/// IMPORTANT OTP/AUTH CONTRACT:
///
/// Firebase Authentication
///      ↓
/// AuthService / OTP Managers
///      ↓
/// verified Firebase UID
///      ↓
/// FirestoreService
///      ↓
/// users/{uid}
///
/// CRITICAL RULE:
///
/// syncAuthenticationProfile() MUST NEVER create a missing
/// users/{uid} document.
///
/// Missing profile creation belongs only to the explicit
/// Create Account / Profile Setup flow.
///
/// GLOBAL DISCOVERY CONTRACT:
///
/// Public discovery supports:
/// - Full Name contains search
/// - Username contains search
/// - JR CALL ID contains search
/// - Email contains search only when explicitly discoverable
/// - Phone contains search only when explicitly discoverable
///
/// Firebase UID is NEVER a public search keyword.
///
/// Search fragments are generated by UserModel and persisted here.
/// This repository guarantees that profile/auth/privacy changes keep
/// the persisted search index synchronized.
///
/// Responsibilities:
///
/// - Create/read/update user profiles.
/// - Real-time profile observation.
/// - Preserve legacy JR CALL profile fields.
/// - Maintain normalized searchable profile fields.
/// - Maintain bounded global searchFragments.
/// - Maintain searchIndexVersion.
/// - Atomic username uniqueness.
/// - Atomic JR CALL public address uniqueness.
/// - Safe reservation ownership.
/// - Remove optional profile fields safely.
/// - Exact username lookup.
/// - Exact JR CALL address lookup.
/// - Global contains-style discovery support.
/// - Legacy name-prefix discovery fallback.
/// - Email/phone discovery where privacy allows.
/// - Authentication metadata synchronization.
/// - Safe profile deletion and reservation cleanup.
///
/// SECURITY:
///
/// - Password is NEVER stored.
/// - OTP is NEVER stored.
/// - Firebase UID remains canonical internal identity.
/// - Firebase UID is NEVER indexed as a public search keyword.
/// - JR CALL public address remains separate.
/// - Phone OTP remains Firebase Authentication-owned.
/// - Email OTP remains backend-owned.
/// - Email discovery requires explicit permission.
/// - Phone discovery requires explicit permission.
/// - Call Engine / Message Engine / WebRTC untouched.
/// ===========================================================

