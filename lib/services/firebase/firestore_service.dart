  // ===========================================================
  // RESERVATION AVAILABILITY
  // ===========================================================

  void _ensureReservationAvailable({
    required DocumentSnapshot<Map<String, dynamic>>? snapshot,
    required String uid,
    required String fieldName,
    required String? value,
  }) {
    if (snapshot == null ||
        !snapshot.exists) {
      return;
    }

    final String? ownerUid =
    _cleanString(
      snapshot.data()?['uid'],
    );

    if (ownerUid == uid) {
      return;
    }

    throw StateError(
      '$fieldName "$value" is already in use.',
    );
  }

  // ===========================================================
  // SAFE RESERVATION DELETE
  // ===========================================================

  void _deleteReservationIfOwned({
    required Transaction transaction,
    required DocumentReference<Map<String, dynamic>>? reference,
    required DocumentSnapshot<Map<String, dynamic>>? snapshot,
    required String ownerUid,
  }) {
    if (reference == null ||
        snapshot == null ||
        !snapshot.exists) {
      return;
    }

    final String? reservationOwner =
    _cleanString(
      snapshot.data()?['uid'],
    );

    if (reservationOwner != ownerUid) {
      return;
    }

    transaction.delete(
      reference,
    );
  }

  // ===========================================================
  // QUERY PARSING
  // ===========================================================

  List<UserModel> _modelsFromQuery(
      QuerySnapshot<Map<String, dynamic>> snapshot, {
        String? excludeUid,
        bool requireDiscoverableEmail = false,
        bool requireDiscoverablePhone = false,
      }) {
    final String? normalizedExclude =
    _cleanString(
      excludeUid,
    );

    final List<UserModel> models =
    <UserModel>[];

    for (final QueryDocumentSnapshot<Map<String, dynamic>>
    document in snapshot.docs) {
      final Map<String, dynamic> data =
      document.data();

      if (!_isGenerallyDiscoverable(
        data,
      )) {
        continue;
      }

      if (requireDiscoverableEmail &&
          !_isDiscoveryFlagAllowed(
            data['isDiscoverableByEmail'],
          )) {
        continue;
      }

      if (requireDiscoverablePhone &&
          !_isDiscoveryFlagAllowed(
            data['isDiscoverableByPhone'],
          )) {
        continue;
      }

      final UserModel model =
      _userModelFromDocument(
        documentId: document.id,
        data: data,
      );

      if (!model.isDiscoverable ||
          model.isDeleted ||
          model.isBlocked ||
          model.uid.trim().isEmpty) {
        continue;
      }

      if (requireDiscoverableEmail &&
          !model.isDiscoverableByEmail) {
        continue;
      }

      if (requireDiscoverablePhone &&
          !model.isDiscoverableByPhone) {
        continue;
      }

      if (normalizedExclude != null &&
          model.uid == normalizedExclude) {
        continue;
      }

      models.add(
        model,
      );
    }

    return List<UserModel>.unmodifiable(
      models,
    );
  }

  void _addQueryModels(
      Map<String, UserModel> results,
      QuerySnapshot<Map<String, dynamic>> snapshot, {
        required int limit,
        String? excludeUid,
        bool requireDiscoverableEmail = false,
        bool requireDiscoverablePhone = false,
      }) {
    if (results.length >= limit) {
      return;
    }

    final List<UserModel> models =
    _modelsFromQuery(
      snapshot,
      excludeUid: excludeUid,
      requireDiscoverableEmail:
      requireDiscoverableEmail,
      requireDiscoverablePhone:
      requireDiscoverablePhone,
    );

    for (final UserModel model in models) {
      if (results.length >= limit) {
        break;
      }

      _addSearchModel(
        results,
        model,
        excludeUid: excludeUid,
      );
    }
  }

  UserModel _userModelFromDocument({
    required String documentId,
    required Map<String, dynamic> data,
  }) {
    final Map<String, dynamic> normalized =
    Map<String, dynamic>.from(
      data,
    );

    final String? storedUid =
    _cleanString(
      normalized['uid'],
    );

    if (storedUid == null) {
      normalized['uid'] =
          documentId;
    }

    normalized['name'] ??=
    normalized['fullName'];

    normalized['phone'] ??=
    normalized['phoneNumber'];

    normalized['userAddress'] ??=
    normalized['jrCallUserId'];

    normalized['photoUrl'] ??=
    normalized['profilePhotoUrl'];

    normalized['coverPhoto'] ??=
        normalized['coverPhotoUrl'] ??
            normalized['backgroundPhotoUrl'];

    return UserModel.fromMap(
      normalized,
    );
  }

  bool _isGenerallyDiscoverable(
      Map<String, dynamic> data,
      ) {
    if (data.containsKey(
      'isDiscoverable',
    ) &&
        !_readBool(
          data['isDiscoverable'],
        )) {
      return false;
    }

    if (_readBool(
      data['isDeleted'],
    )) {
      return false;
    }

    if (_readBool(
      data['isBlocked'],
    )) {
      return false;
    }

    return true;
  }

  // Existing documents without explicit Email/Phone discovery
  // permission remain PRIVATE for those fields.
  bool _isDiscoveryFlagAllowed(
      Object? value,
      ) {
    if (value == null) {
      return false;
    }

    return _readBool(
      value,
    );
  }

  // ===========================================================
  // SEARCH RESULT HELPER
  // ===========================================================

  void _addSearchModel(
      Map<String, UserModel> results,
      UserModel model, {
        String? excludeUid,
      }) {
    final String uid =
    model.uid.trim();

    if (uid.isEmpty ||
        !model.isDiscoverable ||
        model.isDeleted ||
        model.isBlocked) {
      return;
    }

    final String? normalizedExclude =
    _cleanString(
      excludeUid,
    );

    if (normalizedExclude != null &&
        uid == normalizedExclude) {
      return;
    }

    results[uid] = model;
  }

  // ===========================================================
  // PHONE EXACT-MATCH HELPER
  // ===========================================================

  bool _phoneMatchesExactKeys(
      UserModel model,
      Iterable<String> searchKeys,
      ) {
    if (!model.isDiscoverableByPhone) {
      return false;
    }

    final String? normalizedPhone =
        model.phoneNormalized;

    if (normalizedPhone == null) {
      return false;
    }

    final String normalizedDigits =
    _digitsOnlyPhone(
      normalizedPhone,
    );

    for (final String key in searchKeys) {
      final String normalizedKey =
      _normalizePhoneForSearch(
        key,
      );

      final String keyDigits =
      _digitsOnlyPhone(
        key,
      );

      if (normalizedKey.isNotEmpty &&
          normalizedPhone ==
              normalizedKey) {
        return true;
      }

      if (keyDigits.isNotEmpty &&
          normalizedDigits ==
              keyDigits) {
        return true;
      }
    }

    return false;
  }

  // ===========================================================
  // OPTIONAL STRING HELPERS
  // ===========================================================

  void _applyOptionalString(
      Map<String, dynamic> updates, {
        required String field,
        required String value,
      }) {
    final String normalized =
    value.trim();

    if (normalized.isEmpty) {
      updates[field] =
          FieldValue.delete();
    } else {
      updates[field] =
          normalized;
    }
  }

  void _applyMirroredOptionalString(
      Map<String, dynamic> updates, {
        required String primaryField,
        required String compatibilityField,
        required String value,
      }) {
    final String normalized =
    value.trim();

    if (normalized.isEmpty) {
      updates[primaryField] =
          FieldValue.delete();

      updates[compatibilityField] =
          FieldValue.delete();
    } else {
      updates[primaryField] =
          normalized;

      updates[compatibilityField] =
          normalized;
    }
  }

  // ===========================================================
  // UID VALIDATION
  // ===========================================================

  String _requireUid(
      String uid,
      ) {
    final String normalized =
    uid.trim();

    if (normalized.isEmpty) {
      throw ArgumentError.value(
        uid,
        'uid',
        'User UID cannot be empty.',
      );
    }

    return normalized;
  }

