  // ===========================================================
  // GLOBAL SEARCH USERS
  //
  // ORDER:
  //
  // 1. Exact JR CALL ID
  // 2. Exact username
  // 3. Exact full name
  // 4. Exact discoverable email
  // 5. Exact discoverable phone
  // 6. Unified contains-style searchFragments query
  // 7. Legacy name-prefix fallback
  // 8. Rank + deduplicate + limit
  //
  // Firebase UID is NEVER searched.
  // ===========================================================

  Future<List<UserModel>> searchUsers(
      String query, {
        int limit = 20,
        String? excludeUid,
      }) async {
    final String normalizedQuery =
    _normalizeSearchText(
      query,
    );

    if (normalizedQuery.isEmpty) {
      return const <UserModel>[];
    }

    final int safeLimit = _safeSearchLimit(
      limit,
    );

    final int candidateLimit =
    _searchCandidateLimit(
      safeLimit,
    );

    final String? normalizedExcludeUid =
    _cleanString(
      excludeUid,
    );

    final Map<String, UserModel> results =
    <String, UserModel>{};

    // ---------------------------------------------------------
    // EXACT JR CALL ADDRESS
    // ---------------------------------------------------------

    final String? address =
    _normalizeUserAddress(
      query,
    );

    if (address != null) {
      try {
        _validateUserAddress(
          address,
        );

        final DocumentSnapshot<Map<String, dynamic>> reservation =
        await _userAddressReservations
            .doc(address)
            .get();

        final String? uid = _cleanString(
          reservation.data()?['uid'],
        );

        if (uid != null) {
          final UserModel? user =
          await getUser(
            uid,
          );

          if (user != null) {
            _addSearchModel(
              results,
              user,
              excludeUid: normalizedExcludeUid,
            );
          }
        }
      } on ArgumentError {
        // Query is not a valid exact JR CALL ID.
      }
    }

    // ---------------------------------------------------------
    // EXACT USERNAME
    // ---------------------------------------------------------

    final String? username =
    _normalizeUsername(
      query,
    );

    if (username != null) {
      try {
        _validateUsername(
          username,
        );

        final DocumentSnapshot<Map<String, dynamic>> reservation =
        await _usernameReservations
            .doc(username)
            .get();

        final String? uid = _cleanString(
          reservation.data()?['uid'],
        );

        if (uid != null) {
          final UserModel? user =
          await getUser(
            uid,
          );

          if (user != null) {
            _addSearchModel(
              results,
              user,
              excludeUid: normalizedExcludeUid,
            );
          }
        }
      } on ArgumentError {
        // Query is not a valid exact username.
      }
    }

    // ---------------------------------------------------------
    // EXACT FULL NAME
    //
    // Helps exact-name ranking even when a one-character or
    // short fragment could match a very large user population.
    // ---------------------------------------------------------

    try {
      final QuerySnapshot<Map<String, dynamic>> exactNameSnapshot =
      await usersCollection
          .where(
        'isDiscoverable',
        isEqualTo: true,
      )
          .where(
        'normalizedName',
        isEqualTo: normalizedQuery,
      )
          .limit(
        candidateLimit,
      )
          .get();

      _addQueryModels(
        results,
        exactNameSnapshot,
        limit: _maximumSearchLimit,
        excludeUid: normalizedExcludeUid,
      );
    } on FirebaseException catch (error) {
      if (error.code != 'failed-precondition') {
        rethrow;
      }

      // Composite index will be finalized in firestore.indexes.json.
      // Unified searchFragments query below remains authoritative.
    }

    // ---------------------------------------------------------
    // EXACT DISCOVERABLE EMAIL
    // ---------------------------------------------------------

    if (normalizedQuery.contains('@') &&
        _basicEmailPattern.hasMatch(
          normalizedQuery,
        )) {
      final List<UserModel> emailResults =
      await getUsersByEmail(
        normalizedQuery,
        limit: safeLimit,
        excludeUid: normalizedExcludeUid,
      );

      for (final UserModel user in emailResults) {
        _addSearchModel(
          results,
          user,
          excludeUid: normalizedExcludeUid,
        );
      }
    }

    // ---------------------------------------------------------
    // EXACT DISCOVERABLE PHONE
    // ---------------------------------------------------------

    if (_looksLikePhone(
      query,
    )) {
      final List<UserModel> phoneResults =
      await getUsersByPhone(
        query,
        limit: safeLimit,
        excludeUid: normalizedExcludeUid,
      );

      for (final UserModel user in phoneResults) {
        _addSearchModel(
          results,
          user,
          excludeUid: normalizedExcludeUid,
        );
      }
    }

    // ---------------------------------------------------------
    // GLOBAL CONTAINS SEARCH
    //
    // This is the primary production discovery path.
    //
    // Example:
    //
    // Rahibullah
    //
    // Query:
    // r
    // h
    // ib
    // bull
    // ullah
    //
    // can all resolve through searchFragments.
    // ---------------------------------------------------------

    final QuerySnapshot<Map<String, dynamic>>? fragmentSnapshot =
    await _queryDiscoveryFragments(
      query,
      limit: candidateLimit,
    );

    if (fragmentSnapshot != null) {
      _addQueryModels(
        results,
        fragmentSnapshot,
        limit: _maximumSearchLimit,
        excludeUid: normalizedExcludeUid,
      );
    }

    // ---------------------------------------------------------
    // LEGACY NAME PREFIX FALLBACK
    //
    // Old documents that have not yet received searchFragments
    // can still remain discoverable by the previous prefix path.
    //
    // syncAuthenticationProfile(), updateProfile(),
    // updateDiscoverability(), createUser(), clearProfileField()
    // and refreshSearchIndex() progressively self-heal them.
    // ---------------------------------------------------------

    if (results.length < candidateLimit) {
      try {
        final QuerySnapshot<Map<String, dynamic>> snapshot =
        await usersCollection
            .where(
          'isDiscoverable',
          isEqualTo: true,
        )
            .where(
          'normalizedName',
          isGreaterThanOrEqualTo:
          normalizedQuery,
        )
            .where(
          'normalizedName',
          isLessThanOrEqualTo:
          '$normalizedQuery\uf8ff',
        )
            .limit(
          candidateLimit - results.length,
        )
            .get();

        _addQueryModels(
          results,
          snapshot,
          limit: _maximumSearchLimit,
          excludeUid: normalizedExcludeUid,
        );
      } on FirebaseException catch (error) {
        if (error.code != 'failed-precondition') {
          rethrow;
        }

        // Index is finalized later in firestore.indexes.json.
      }
    }

    // ---------------------------------------------------------
    // FULL QUERY VERIFICATION
    //
    // searchFragments uses a bounded lookup fragment for long
    // values. Therefore the complete original query is verified
    // locally against the small bounded server result set.
    //
    // This is NOT "download every user and filter locally".
    // ---------------------------------------------------------

    final List<UserModel> matching =
    results.values
        .where(
          (
          UserModel model,
          ) =>
          _matchesSearchQuery(
            model,
            query,
          ),
    )
        .toList(
      growable: false,
    );

    matching.sort(
          (
          UserModel first,
          UserModel second,
          ) {
        final int firstRank =
        _searchRank(
          first,
          query,
        );

        final int secondRank =
        _searchRank(
          second,
          query,
        );

        final int rankComparison =
        firstRank.compareTo(
          secondRank,
        );

        if (rankComparison != 0) {
          return rankComparison;
        }

        final int nameComparison =
        first.fullNameLowercase.compareTo(
          second.fullNameLowercase,
        );

        if (nameComparison != 0) {
          return nameComparison;
        }

        return first.uid.compareTo(
          second.uid,
        );
      },
    );

    return List<UserModel>.unmodifiable(
      matching.take(
        safeLimit,
      ),
    );
  }

  // ===========================================================
  // DELETE USER PROFILE
  // ===========================================================

  Future<void> deleteUserProfile(
      String uid,
      ) async {
    final String normalizedUid =
    uid.trim();

    if (normalizedUid.isEmpty) {
      return;
    }

    final DocumentReference<Map<String, dynamic>> userRef =
    usersCollection.doc(
      normalizedUid,
    );

    await _firestore.runTransaction<void>(
          (
          Transaction transaction,
          ) async {
        final DocumentSnapshot<Map<String, dynamic>> userSnapshot =
        await transaction.get(
          userRef,
        );

        final Map<String, dynamic>? data =
        userSnapshot.data();

        if (!userSnapshot.exists ||
            data == null) {
          return;
        }

        final String? username =
        _normalizeUsername(
          data['username'],
        );

        final String? address =
        _normalizeUserAddress(
          data['userAddress'] ??
              data['jrCallUserId'],
        );

        final DocumentReference<Map<String, dynamic>>? usernameRef =
        username == null
            ? null
            : _usernameReservations.doc(
          username,
        );

        final DocumentReference<Map<String, dynamic>>? addressRef =
        address == null
            ? null
            : _userAddressReservations.doc(
          address,
        );

        DocumentSnapshot<Map<String, dynamic>>? usernameSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? addressSnapshot;

        if (usernameRef != null) {
          usernameSnapshot = await transaction.get(
            usernameRef,
          );
        }

        if (addressRef != null) {
          addressSnapshot = await transaction.get(
            addressRef,
          );
        }

        // -------------------------------------------------------
        // ALL READS COMPLETE.
        // -------------------------------------------------------

        _deleteReservationIfOwned(
          transaction: transaction,
          reference: usernameRef,
          snapshot: usernameSnapshot,
          ownerUid: normalizedUid,
        );

        _deleteReservationIfOwned(
          transaction: transaction,
          reference: addressRef,
          snapshot: addressSnapshot,
          ownerUid: normalizedUid,
        );

        transaction.delete(
          userRef,
        );
      },
    );
  }

  // ===========================================================
  // MAIN USER DOCUMENT BUILDER
  // ===========================================================

  Map<String, dynamic> _buildUserDocument(
      UserModel user, {
        required String? normalizedUsername,
        required String? normalizedUserAddress,
        required bool existingDocument,
      }) {
    final Map<String, dynamic> data =
    Map<String, dynamic>.from(
      user.toMap(),
    );

    final String uid = _requireUid(
      user.uid,
    );

    final String fullName =
    user.name.trim();

    final String normalizedName =
    _normalizeSearchText(
      fullName,
    );

    final String phone =
    user.phone.trim();

    final String? email =
    _cleanString(
      user.email,
    );

    data['uid'] = uid;

    // ---------------------------------------------------------
    // NAME
    // ---------------------------------------------------------

    data['name'] = fullName;
    data['fullName'] = fullName;
    data['normalizedName'] = normalizedName;
    data['fullNameLowercase'] = normalizedName;

    // ---------------------------------------------------------
    // PHONE
    // ---------------------------------------------------------

    data['phone'] = phone;
    data['phoneNumber'] = phone;

    if (phone.isEmpty) {
      data['phoneNormalized'] =
          FieldValue.delete();

      data['phoneDigits'] =
          FieldValue.delete();

      data['phoneSearchKeys'] =
          FieldValue.delete();
    } else {
      data['phoneNormalized'] =
          _normalizePhoneForSearch(
            phone,
          );

      data['phoneDigits'] =
          _digitsOnlyPhone(
            phone,
          );

      data['phoneSearchKeys'] =
          _phoneSearchKeys(
            phone,
          );
    }

    // ---------------------------------------------------------
    // EMAIL
    // ---------------------------------------------------------

    if (email == null) {
      data['email'] =
          FieldValue.delete();

      data['emailNormalized'] =
          FieldValue.delete();
    } else {
      _validateEmail(
        email,
      );

      data['email'] = email;

      data['emailNormalized'] =
          email.toLowerCase();
    }

    // ---------------------------------------------------------
    // USERNAME
    // ---------------------------------------------------------

    if (normalizedUsername == null) {
      data['username'] =
          FieldValue.delete();

      data['normalizedUsername'] =
          FieldValue.delete();

      data['usernameLowercase'] =
          FieldValue.delete();
    } else {
      data['username'] =
          normalizedUsername;

      data['normalizedUsername'] =
          normalizedUsername;

      data['usernameLowercase'] =
          normalizedUsername;
    }

    // ---------------------------------------------------------
    // JR CALL ID
    // ---------------------------------------------------------

    if (normalizedUserAddress == null) {
      data['userAddress'] =
          FieldValue.delete();

      data['normalizedUserAddress'] =
          FieldValue.delete();

      data['jrCallUserId'] =
          FieldValue.delete();

      data['jrCallUserIdLowercase'] =
          FieldValue.delete();
    } else {
      data['userAddress'] =
          normalizedUserAddress;

      data['normalizedUserAddress'] =
          normalizedUserAddress;

      data['jrCallUserId'] =
          normalizedUserAddress;

      data['jrCallUserIdLowercase'] =
          normalizedUserAddress;
    }

    // ---------------------------------------------------------
    // MEDIA COMPATIBILITY
    // ---------------------------------------------------------

    final String? profilePhoto =
    _cleanString(
      user.photoUrl,
    );

    if (profilePhoto == null) {
      data.remove(
        'profilePhotoUrl',
      );
    } else {
      data['profilePhotoUrl'] =
          profilePhoto;
    }

    final String? coverPhoto =
    _cleanString(
      user.coverPhoto,
    );

    if (coverPhoto == null) {
      data.remove(
        'coverPhotoUrl',
      );

      data.remove(
        'backgroundPhotoUrl',
      );
    } else {
      data['coverPhotoUrl'] =
          coverPhoto;

      data['backgroundPhotoUrl'] =
          coverPhoto;
    }

    // ---------------------------------------------------------
    // DISCOVERABILITY
    //
    // FILE 1 owns safe defaults.
    //
    // Email/Phone discovery is NOT silently enabled here.
    // ---------------------------------------------------------

    data['isDiscoverable'] =
        user.isDiscoverable;

    data['isDiscoverableByEmail'] =
        user.isDiscoverableByEmail;

    data['isDiscoverableByPhone'] =
        user.isDiscoverableByPhone;

    // ---------------------------------------------------------
    // GLOBAL SEARCH INDEX
    //
    // Recalculate AFTER canonical field normalization.
    // ---------------------------------------------------------

    _applySearchIndexToDocument(
      uid: uid,
      document: data,
    );

    data.removeWhere(
          (
          String key,
          dynamic value,
          ) =>
      value == null,
    );

    if (existingDocument) {
      data.remove(
        'createdAt',
      );
    } else {
      data['createdAt'] =
          Timestamp.fromDate(
            user.createdAt,
          );
    }

    data['updatedAt'] =
        FieldValue.serverTimestamp();

    return data;
  }

