  // ===========================================================
  // AUTHENTICATION METADATA SYNC
  //
  // CRITICAL OTP MASTER RULE:
  //
  // This method updates EXISTING JR CALL profiles only.
  //
  // It MUST NOT:
  // - create users/{uid};
  // - create placeholder profile;
  // - create incomplete profile after OTP;
  // - bypass Profile Setup;
  // - convert Login into Signup.
  //
  // SEARCH:
  // Authentication synchronization also self-heals the current
  // search index for an existing profile.
  // ===========================================================

  Future<void> syncAuthenticationProfile({
    required String uid,
    String? email,
    String? phoneNumber,
    bool? emailVerified,
    bool? phoneVerified,
    List<String>? signInProviders,
  }) async {
    final String normalizedUid = _requireUid(
      uid,
    );

    final DocumentReference<Map<String, dynamic>> userRef =
    usersCollection.doc(
      normalizedUid,
    );

    final Map<String, dynamic> baseUpdates =
    <String, dynamic>{
      'updatedAt': FieldValue.serverTimestamp(),
    };

    // =========================================================
    // EMAIL AUTH METADATA
    // =========================================================

    if (email != null) {
      final String normalized = email.trim();

      if (normalized.isEmpty) {
        baseUpdates['email'] = FieldValue.delete();
        baseUpdates['emailNormalized'] = FieldValue.delete();
      } else {
        _validateEmail(
          normalized,
        );

        baseUpdates['email'] = normalized;
        baseUpdates['emailNormalized'] =
            normalized.toLowerCase();
      }
    }

    // =========================================================
    // PHONE AUTH METADATA
    // =========================================================

    if (phoneNumber != null) {
      final String normalized = phoneNumber.trim();

      if (normalized.isEmpty) {
        baseUpdates['phone'] = '';
        baseUpdates['phoneNumber'] = '';
        baseUpdates['phoneNormalized'] = FieldValue.delete();
        baseUpdates['phoneDigits'] = FieldValue.delete();
        baseUpdates['phoneSearchKeys'] = FieldValue.delete();
      } else {
        final String normalizedPhone =
        _normalizePhoneForSearch(
          normalized,
        );

        final List<String> searchKeys =
        _phoneSearchKeys(
          normalized,
        );

        baseUpdates['phone'] = normalized;
        baseUpdates['phoneNumber'] = normalized;
        baseUpdates['phoneNormalized'] = normalizedPhone;
        baseUpdates['phoneDigits'] = _digitsOnlyPhone(
          normalized,
        );

        // IMPORTANT:
        // Replace the old list.
        //
        // Do NOT use arrayUnion here because a changed phone number
        // must not leave an old number searchable forever.
        baseUpdates['phoneSearchKeys'] = searchKeys;
      }
    }

    if (emailVerified != null) {
      baseUpdates['emailVerified'] =
          emailVerified;
    }

    if (phoneVerified != null) {
      baseUpdates['phoneVerified'] =
          phoneVerified;
    }

    if (signInProviders != null) {
      final List<String> providers =
      signInProviders
          .map(
            (
            String value,
            ) =>
            value.trim(),
      )
          .where(
            (
            String value,
            ) =>
        value.isNotEmpty,
      )
          .toSet()
          .toList(
        growable: false,
      );

      baseUpdates['signInProviders'] =
          providers;
    }

    // ---------------------------------------------------------
    // EXISTING PROFILE ONLY.
    //
    // Transaction prevents a race where a profile disappears
    // between existence-check and update.
    // ---------------------------------------------------------

    await _firestore.runTransaction<void>(
          (
          Transaction transaction,
          ) async {
        final DocumentSnapshot<Map<String, dynamic>> snapshot =
        await transaction.get(
          userRef,
        );

        final Map<String, dynamic>? currentData =
        snapshot.data();

        if (!snapshot.exists ||
            currentData == null) {
          throw StateError(
            'JR CALL user profile does not exist. '
                'Authentication metadata cannot create a profile.',
          );
        }

        final Map<String, dynamic> updates =
        Map<String, dynamic>.from(
          baseUpdates,
        );

        final Map<String, dynamic> searchData =
        Map<String, dynamic>.from(
          currentData,
        );

        searchData['uid'] = normalizedUid;

        if (email != null) {
          final String normalized = email.trim();

          if (normalized.isEmpty) {
            searchData.remove('email');
            searchData.remove('emailNormalized');
          } else {
            searchData['email'] = normalized;
            searchData['emailNormalized'] =
                normalized.toLowerCase();
          }
        }

        if (phoneNumber != null) {
          final String normalized =
          phoneNumber.trim();

          if (normalized.isEmpty) {
            searchData['phone'] = '';
            searchData['phoneNumber'] = '';
            searchData.remove('phoneNormalized');
            searchData.remove('phoneDigits');
            searchData.remove('phoneSearchKeys');
          } else {
            searchData['phone'] = normalized;
            searchData['phoneNumber'] = normalized;
            searchData['phoneNormalized'] =
                _normalizePhoneForSearch(
                  normalized,
                );
            searchData['phoneDigits'] =
                _digitsOnlyPhone(
                  normalized,
                );
            searchData['phoneSearchKeys'] =
                _phoneSearchKeys(
                  normalized,
                );
          }
        }

        _applySearchIndexToUpdates(
          uid: normalizedUid,
          searchData: searchData,
          updates: updates,
        );

        transaction.update(
          userRef,
          updates,
        );
      },
    );
  }

