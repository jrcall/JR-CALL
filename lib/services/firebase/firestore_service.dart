  int _safeSearchLimit(
      int value,
      ) {
    if (value < 1) {
      return 1;
    }

    if (value >
        _maximumSearchLimit) {
      return _maximumSearchLimit;
    }

    return value;
  }

  int _searchCandidateLimit(
      int requestedLimit,
      ) {
    final int safeLimit =
    _safeSearchLimit(
      requestedLimit,
    );

    final int expanded =
        safeLimit * 3;

    if (expanded >
        _maximumSearchLimit) {
      return _maximumSearchLimit;
    }

    return expanded < safeLimit
        ? safeLimit
        : expanded;
  }

  DateTime _dateOnly(
      DateTime value,
      ) {
    return DateTime(
      value.year,
      value.month,
      value.day,
    );
  }

  String? _cleanString(
      Object? value,
      ) {
    if (value is! String) {
      return null;
    }

    final String normalized =
    value.trim();

    return normalized.isEmpty
        ? null
        : normalized;
  }

  bool _readBool(
      Object? value,
      ) {
    if (value is bool) {
      return value;
    }

    if (value is num) {
      return value != 0;
    }

    if (value is String) {
      final String normalized =
      value
          .trim()
          .toLowerCase();

      if (normalized == 'true' ||
          normalized == '1' ||
          normalized == 'yes') {
        return true;
      }

      if (normalized == 'false' ||
          normalized == '0' ||
          normalized == 'no') {
        return false;
      }
    }

    return false;
  }
