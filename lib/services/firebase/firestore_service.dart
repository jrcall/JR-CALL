  // ===========================================================
  // UNIFIED DISCOVERY QUERY
  //
  // Firestore performs indexed candidate lookup.
  // The application only verifies/ranks the bounded result set.
  // ===========================================================

  Future<QuerySnapshot<Map<String, dynamic>>?> _queryDiscoveryFragments(
      String query, {
        required int limit,
      }) async {
    final List<String> fragments =
    _searchLookupFragments(
      query,
    );

    if (fragments.isEmpty) {
      return null;
    }

    final int safeLimit =
    _safeSearchLimit(
      limit,
    );

    Query<Map<String, dynamic>> firestoreQuery =
    usersCollection.where(
      'isDiscoverable',
      isEqualTo: true,
    );

    if (fragments.length == 1) {
      firestoreQuery =
          firestoreQuery.where(
            'searchFragments',
            arrayContains: fragments.first,
          );
    } else {
      firestoreQuery =
          firestoreQuery.where(
            'searchFragments',
            arrayContainsAny: fragments,
          );
    }

    return firestoreQuery
        .limit(
      safeLimit,
    )
        .get();
  }

  // ===========================================================
  // SEARCH LOOKUP NORMALIZATION
  // ===========================================================

  List<String> _searchLookupFragments(
      String query,
      ) {
    final Set<String> values =
    <String>{};

    void addCandidate(
        String? value,
        ) {
      if (value == null ||
          value.isEmpty) {
        return;
      }

      final String bounded =
      _boundSearchFragment(
        value,
      );

      if (bounded.isNotEmpty) {
        values.add(
          bounded,
        );
      }
    }

    final String normalizedText =
    _normalizeSearchText(
      query,
    );

    addCandidate(
      normalizedText,
    );

    final String identity =
    _normalizePublicIdentityQuery(
      query,
    );

    if (identity != normalizedText) {
      addCandidate(
        identity,
      );
    }

    final String? phoneCandidate =
    _normalizePhoneSearchQuery(
      query,
    );

    addCandidate(
      phoneCandidate,
    );

    final List<String> result =
    values
        .take(
      _maximumArrayContainsAnyValues,
    )
        .toList(
      growable: false,
    );

    return List<String>.unmodifiable(
      result,
    );
  }

  String _boundSearchFragment(
      String value,
      ) {
    final List<int> runes =
    value.runes
        .take(
      UserModel.searchFragmentMaxRunes,
    )
        .toList(
      growable: false,
    );

    if (runes.isEmpty) {
      return '';
    }

    return String.fromCharCodes(
      runes,
    );
  }

  // ===========================================================
  // SEARCH QUERY MATCHING
  // ===========================================================

  bool _matchesSearchQuery(
      UserModel model,
      String query,
      ) {
    if (!model.isDiscoverable ||
        !model.isActive) {
      return false;
    }

    final String textQuery =
    _normalizeSearchText(
      query,
    );

    if (textQuery.isEmpty) {
      return false;
    }

    if (model.fullNameLowercase.contains(
      textQuery,
    )) {
      return true;
    }

    final String identityQuery =
    _normalizePublicIdentityQuery(
      query,
    );

    if (identityQuery.isNotEmpty) {
      final String? username =
          model.usernameLowercase;

      if (username != null &&
          username.contains(
            identityQuery,
          )) {
        return true;
      }

      final String? jrCallId =
          model.jrCallUserIdLowercase;

      if (jrCallId != null &&
          jrCallId.contains(
            identityQuery,
          )) {
        return true;
      }
    }

    if (model.isDiscoverableByEmail) {
      final String? email =
          model.emailNormalized;

      if (email != null &&
          email.contains(
            textQuery,
          )) {
        return true;
      }
    }

    if (model.isDiscoverableByPhone) {
      final String? phone =
          model.phoneNormalized;

      final String? phoneQuery =
      _normalizePhoneSearchQuery(
        query,
      );

      if (phone != null &&
          phoneQuery != null &&
          phone.contains(
            phoneQuery,
          )) {
        return true;
      }

      final String queryDigits =
      _digitsOnlyPhone(
        query,
      );

      final String phoneDigits =
      _digitsOnlyPhone(
        phone ?? '',
      );

      if (queryDigits.isNotEmpty &&
          phoneDigits.contains(
            queryDigits,
          )) {
        return true;
      }
    }

    return false;
  }

  // ===========================================================
  // SEARCH RESULT RANKING
  //
  // Lower number = stronger match.
  // ===========================================================

  int _searchRank(
      UserModel model,
      String query,
      ) {
    final String textQuery =
    _normalizeSearchText(
      query,
    );

    final String identityQuery =
    _normalizePublicIdentityQuery(
      query,
    );

    final String? username =
        model.usernameLowercase;

    final String? jrCallId =
        model.jrCallUserIdLowercase;

    final String? email =
        model.emailNormalized;

    final String? phone =
        model.phoneNormalized;

    final String? phoneQuery =
    _normalizePhoneSearchQuery(
      query,
    );

    // ---------------------------------------------------------
    // EXACT UNIQUE PUBLIC IDENTITIES
    // ---------------------------------------------------------

    if (identityQuery.isNotEmpty &&
        jrCallId == identityQuery) {
      return 0;
    }

    if (identityQuery.isNotEmpty &&
        username == identityQuery) {
      return 1;
    }

    // ---------------------------------------------------------
    // EXACT FULL NAME
    // ---------------------------------------------------------

    if (model.fullNameLowercase ==
        textQuery) {
      return 2;
    }

    // ---------------------------------------------------------
    // EXACT EMAIL / PHONE
    // ---------------------------------------------------------

    if (model.isDiscoverableByEmail &&
        email == textQuery) {
      return 3;
    }

    if (model.isDiscoverableByPhone &&
        phoneQuery != null &&
        _phoneMatchesExactKeys(
          model,
          _phoneSearchKeys(
            query,
          ),
        )) {
      return 4;
    }

    // ---------------------------------------------------------
    // PREFIX MATCHES
    // ---------------------------------------------------------

    if (model.fullNameLowercase.startsWith(
      textQuery,
    )) {
      return 10;
    }

    if (identityQuery.isNotEmpty &&
        username != null &&
        username.startsWith(
          identityQuery,
        )) {
      return 11;
    }

    if (identityQuery.isNotEmpty &&
        jrCallId != null &&
        jrCallId.startsWith(
          identityQuery,
        )) {
      return 12;
    }

    if (model.isDiscoverableByEmail &&
        email != null &&
        email.startsWith(
          textQuery,
        )) {
      return 13;
    }

    if (model.isDiscoverableByPhone &&
        phone != null &&
        phoneQuery != null &&
        phone.startsWith(
          phoneQuery,
        )) {
      return 14;
    }

    // ---------------------------------------------------------
    // CONTAINS MATCHES
    // ---------------------------------------------------------

    return 20;
  }

