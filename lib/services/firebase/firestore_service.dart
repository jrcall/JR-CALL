  Future<void> createUser(
      UserModel user,
      ) async {
    final String uid = _requireUid(
      user.uid,
    );

    final String? requestedUsername = _normalizeUsername(
      user.username,
    );

    final String? requestedAddress = _normalizeUserAddress(
      user.userAddress,
    );

    _validateUsername(
      requestedUsername,
    );

    _validateUserAddress(
      requestedAddress,
    );

    final DocumentReference<Map<String, dynamic>> userRef =
    usersCollection.doc(
      uid,
    );

    await _firestore.runTransaction<void>(
          (
          Transaction transaction,
          ) async {
        // -------------------------------------------------------
        // ALL TRANSACTION READS MUST HAPPEN BEFORE WRITES.
        // -------------------------------------------------------

        final DocumentSnapshot<Map<String, dynamic>> currentUserSnapshot =
        await transaction.get(
          userRef,
        );

        final Map<String, dynamic>? currentData =
        currentUserSnapshot.data();

        final String? currentUsername = _normalizeUsername(
          currentData?['username'],
        );

        final String? currentAddress = _normalizeUserAddress(
          currentData?['userAddress'] ??
              currentData?['jrCallUserId'],
        );

        final DocumentReference<Map<String, dynamic>>? newUsernameRef =
        requestedUsername == null
            ? null
            : _usernameReservations.doc(
          requestedUsername,
        );

        final DocumentReference<Map<String, dynamic>>? newAddressRef =
        requestedAddress == null
            ? null
            : _userAddressReservations.doc(
          requestedAddress,
        );

        final DocumentReference<Map<String, dynamic>>? oldUsernameRef =
        currentUsername != null &&
            currentUsername != requestedUsername
            ? _usernameReservations.doc(
          currentUsername,
        )
            : null;

        final DocumentReference<Map<String, dynamic>>? oldAddressRef =
        currentAddress != null &&
            currentAddress != requestedAddress
            ? _userAddressReservations.doc(
          currentAddress,
        )
            : null;

        DocumentSnapshot<Map<String, dynamic>>? newUsernameSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? newAddressSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? oldUsernameSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? oldAddressSnapshot;

        if (newUsernameRef != null) {
          newUsernameSnapshot = await transaction.get(
            newUsernameRef,
          );
        }

        if (newAddressRef != null) {
          newAddressSnapshot = await transaction.get(
            newAddressRef,
          );
        }

        if (oldUsernameRef != null) {
          oldUsernameSnapshot = await transaction.get(
            oldUsernameRef,
          );
        }

        if (oldAddressRef != null) {
          oldAddressSnapshot = await transaction.get(
            oldAddressRef,
          );
        }

        // -------------------------------------------------------
        // ALL WRITES START BELOW THIS POINT.
        // -------------------------------------------------------

        _ensureReservationAvailable(
          snapshot: newUsernameSnapshot,
          uid: uid,
          fieldName: 'Username',
          value: requestedUsername,
        );

        _ensureReservationAvailable(
          snapshot: newAddressSnapshot,
          uid: uid,
          fieldName: 'JR CALL User Address',
          value: requestedAddress,
        );

        _deleteReservationIfOwned(
          transaction: transaction,
          reference: oldUsernameRef,
          snapshot: oldUsernameSnapshot,
          ownerUid: uid,
        );

        _deleteReservationIfOwned(
          transaction: transaction,
          reference: oldAddressRef,
          snapshot: oldAddressSnapshot,
          ownerUid: uid,
        );

        if (newUsernameRef != null &&
            requestedUsername != null) {
          transaction.set(
            newUsernameRef,
            _reservationDocument(
              uid: uid,
              value: requestedUsername,
              existing: newUsernameSnapshot?.exists ?? false,
            ),
            SetOptions(
              merge: true,
            ),
          );
        }

        if (newAddressRef != null &&
            requestedAddress != null) {
          transaction.set(
            newAddressRef,
            _reservationDocument(
              uid: uid,
              value: requestedAddress,
              existing: newAddressSnapshot?.exists ?? false,
            ),
            SetOptions(
              merge: true,
            ),
          );
        }

        final Map<String, dynamic> document = _buildUserDocument(
          user,
          normalizedUsername: requestedUsername,
          normalizedUserAddress: requestedAddress,
          existingDocument: currentUserSnapshot.exists,
        );

        transaction.set(
          userRef,
          document,
          SetOptions(
            merge: true,
          ),
        );
      },
    );
  }

  // ===========================================================
  // READ USER
  // ===========================================================

  Future<UserModel?> getUser(
      String uid,
      ) async {
    final String normalizedUid = uid.trim();

    if (normalizedUid.isEmpty) {
      return null;
    }

    final DocumentSnapshot<Map<String, dynamic>> snapshot =
    await usersCollection
        .doc(normalizedUid)
        .get();

    final Map<String, dynamic>? data = snapshot.data();

    if (!snapshot.exists ||
        data == null) {
      return null;
    }

    return _userModelFromDocument(
      documentId: snapshot.id,
      data: data,
    );
  }

  // ===========================================================
  // WATCH USER
  // ===========================================================

  Stream<UserModel?> watchUser(
      String uid,
      ) {
    final String normalizedUid = uid.trim();

    if (normalizedUid.isEmpty) {
      return Stream<UserModel?>.value(
        null,
      );
    }

    return usersCollection
        .doc(normalizedUid)
        .snapshots()
        .map(
          (
          DocumentSnapshot<Map<String, dynamic>> snapshot,
          ) {
        final Map<String, dynamic>? data = snapshot.data();

        if (!snapshot.exists ||
            data == null) {
          return null;
        }

        return _userModelFromDocument(
          documentId: snapshot.id,
          data: data,
        );
      },
    );
  }

