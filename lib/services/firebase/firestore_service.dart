  // ===========================================================
  // EMAIL DISCOVERY
  //
  // Unified searchFragments index is used.
  // Email is returned only if:
  // - account is globally discoverable;
  // - account explicitly permits email discovery;
  // - normalized email exactly matches.
  // ===========================================================

  Future<List<UserModel>> getUsersByEmail(
      String email, {
        int limit = 10,
        String? excludeUid,
      }) async {
    final String normalized =
    email
        .trim()
        .toLowerCase();

    if (normalized.isEmpty ||
        !_basicEmailPattern.hasMatch(
          normalized,
        )) {
      return const <UserModel>[];
    }

    final int safeLimit = _safeSearchLimit(
      limit,
    );

    final QuerySnapshot<Map<String, dynamic>>? snapshot =
    await _queryDiscoveryFragments(
      normalized,
      limit: _searchCandidateLimit(
        safeLimit,
      ),
    );

    if (snapshot == null) {
      return const <UserModel>[];
    }

    final List<UserModel> models =
    _modelsFromQuery(
      snapshot,
      excludeUid: excludeUid,
      requireDiscoverableEmail: true,
    );

    final List<UserModel> matching =
    models
        .where(
          (
          UserModel model,
          ) =>
      model.emailNormalized ==
          normalized,
    )
        .take(
      safeLimit,
    )
        .toList(
      growable: false,
    );

    return List<UserModel>.unmodifiable(
      matching,
    );
  }

