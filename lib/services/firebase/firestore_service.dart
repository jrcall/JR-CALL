  // ===========================================================
  // GENERAL PROFILE VALIDATION
  // ===========================================================

  void _validateProfileInput({
    String? name,
    String? phone,
    String? email,
    String? photoUrl,
    String? coverPhoto,
    String? bio,
    String? country,
    String? countryCode,
    String? gender,
    String? provider,
    String? deviceToken,
    DateTime? dateOfBirth,
  }) {
    if (name != null &&
        name.trim().length > 80) {
      throw ArgumentError(
        'Full name cannot exceed 80 characters.',
      );
    }

    if (phone != null &&
        phone.trim().length > 32) {
      throw ArgumentError(
        'Phone number is too long.',
      );
    }

    if (email != null) {
      final String normalized =
      email.trim();

      if (normalized.length > 254) {
        throw ArgumentError(
          'Email address is too long.',
        );
      }

      if (normalized.isNotEmpty) {
        _validateEmail(
          normalized,
        );
      }
    }

    if (bio != null &&
        bio.trim().length > 300) {
      throw ArgumentError(
        'Bio cannot exceed 300 characters.',
      );
    }

    if (country != null &&
        country.trim().length > 80) {
      throw ArgumentError(
        'Country cannot exceed 80 characters.',
      );
    }

    if (countryCode != null) {
      final String normalized =
      countryCode.trim();

      if (normalized.length > 8) {
        throw ArgumentError(
          'Country code is invalid.',
        );
      }
    }

    if (gender != null &&
        gender.trim().length > 40) {
      throw ArgumentError(
        'Gender value is too long.',
      );
    }

    if (provider != null &&
        provider.trim().length > 80) {
      throw ArgumentError(
        'Provider value is too long.',
      );
    }

    if (deviceToken != null &&
        deviceToken.trim().length > 4096) {
      throw ArgumentError(
        'Device token is invalid.',
      );
    }

    _validateUrlLength(
      photoUrl,
      fieldName:
      'Profile photo URL',
    );

    _validateUrlLength(
      coverPhoto,
      fieldName:
      'Cover photo URL',
    );

    if (dateOfBirth != null) {
      final DateTime today =
      _dateOnly(
        DateTime.now(),
      );

      final DateTime birthDate =
      _dateOnly(
        dateOfBirth,
      );

      if (birthDate.isAfter(
        today,
      )) {
        throw ArgumentError(
          'Date of birth cannot be in the future.',
        );
      }

      if (birthDate.year < 1900) {
        throw ArgumentError(
          'Date of birth is invalid.',
        );
      }
    }
  }

  void _validateEmail(
      String value,
      ) {
    if (!_basicEmailPattern.hasMatch(
      value.trim(),
    )) {
      throw ArgumentError(
        'Email address format is invalid.',
      );
    }
  }

  void _validateUrlLength(
      String? value, {
        required String fieldName,
      }) {
    if (value == null) {
      return;
    }

    final String normalized =
    value.trim();

    if (normalized.length > 4096) {
      throw ArgumentError(
        '$fieldName is too long.',
      );
    }
  }

