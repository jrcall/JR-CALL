  // ===========================================================
  // UPDATE PROFILE
  // ===========================================================

  Future<void> updateProfile({
    required String uid,
    String? name,
    String? phone,
    String? email,
    String? username,
    String? userAddress,
    String? photoUrl,
    String? coverPhoto,
    String? bio,
    String? country,
    String? countryCode,
    String? gender,
    DateTime? dateOfBirth,
    String? provider,
    String? deviceToken,
  }) async {
    final String normalizedUid = _requireUid(
      uid,
    );

    _validateProfileInput(
      name: name,
      phone: phone,
      email: email,
      photoUrl: photoUrl,
      coverPhoto: coverPhoto,
      bio: bio,
      country: country,
      countryCode: countryCode,
      gender: gender,
      provider: provider,
      deviceToken: deviceToken,
      dateOfBirth: dateOfBirth,
    );

    final DocumentReference<Map<String, dynamic>> userRef =
    usersCollection.doc(
      normalizedUid,
    );

    await _firestore.runTransaction<void>(
          (
          Transaction transaction,
          ) async {
        // -------------------------------------------------------
        // READ CURRENT PROFILE FIRST.
        // -------------------------------------------------------

        final DocumentSnapshot<Map<String, dynamic>> userSnapshot =
        await transaction.get(
          userRef,
        );

        final Map<String, dynamic>? currentData =
        userSnapshot.data();

        if (!userSnapshot.exists ||
            currentData == null) {
          throw StateError(
            'User profile does not exist.',
          );
        }

        final String? currentUsername = _normalizeUsername(
          currentData['username'],
        );

        final String? currentAddress = _normalizeUserAddress(
          currentData['userAddress'] ??
              currentData['jrCallUserId'],
        );

        final String? requestedUsername = username == null
            ? currentUsername
            : _normalizeUsername(
          username,
        );

        final String? requestedAddress = userAddress == null
            ? currentAddress
            : _normalizeUserAddress(
          userAddress,
        );

        _validateUsername(
          requestedUsername,
        );

        _validateUserAddress(
          requestedAddress,
        );

        final bool usernameChanged =
            username != null &&
                requestedUsername != currentUsername;

        final bool addressChanged =
            userAddress != null &&
                requestedAddress != currentAddress;

        final DocumentReference<Map<String, dynamic>>? newUsernameRef =
        usernameChanged &&
            requestedUsername != null
            ? _usernameReservations.doc(
          requestedUsername,
        )
            : null;

        final DocumentReference<Map<String, dynamic>>? oldUsernameRef =
        usernameChanged &&
            currentUsername != null
            ? _usernameReservations.doc(
          currentUsername,
        )
            : null;

        final DocumentReference<Map<String, dynamic>>? newAddressRef =
        addressChanged &&
            requestedAddress != null
            ? _userAddressReservations.doc(
          requestedAddress,
        )
            : null;

        final DocumentReference<Map<String, dynamic>>? oldAddressRef =
        addressChanged &&
            currentAddress != null
            ? _userAddressReservations.doc(
          currentAddress,
        )
            : null;

        DocumentSnapshot<Map<String, dynamic>>? newUsernameSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? oldUsernameSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? newAddressSnapshot;

        DocumentSnapshot<Map<String, dynamic>>? oldAddressSnapshot;

        if (newUsernameRef != null) {
          newUsernameSnapshot = await transaction.get(
            newUsernameRef,
          );
        }

        if (oldUsernameRef != null) {
          oldUsernameSnapshot = await transaction.get(
            oldUsernameRef,
          );
        }

        if (newAddressRef != null) {
          newAddressSnapshot = await transaction.get(
            newAddressRef,
          );
        }

        if (oldAddressRef != null) {
          oldAddressSnapshot = await transaction.get(
            oldAddressRef,
          );
        }

        // -------------------------------------------------------
        // ALL TRANSACTION READS ARE COMPLETE.
        // -------------------------------------------------------

        if (usernameChanged &&
            requestedUsername != null) {
          _ensureReservationAvailable(
            snapshot: newUsernameSnapshot,
            uid: normalizedUid,
            fieldName: 'Username',
            value: requestedUsername,
          );
        }

        if (addressChanged &&
            requestedAddress != null) {
          _ensureReservationAvailable(
            snapshot: newAddressSnapshot,
            uid: normalizedUid,
            fieldName: 'JR CALL User Address',
            value: requestedAddress,
          );
        }

        final Map<String, dynamic> updates =
        <String, dynamic>{
          'updatedAt': FieldValue.serverTimestamp(),
        };

        // This map contains real field values only.
        // It is used to rebuild UserModel.searchFragments safely.
        final Map<String, dynamic> searchData =
        Map<String, dynamic>.from(
          currentData,
        );

        searchData['uid'] = normalizedUid;

        // =====================================================
        // NAME
        // =====================================================

        if (name != null) {
          final String value = name.trim();

          final String normalizedName = _normalizeSearchText(
            value,
          );

          updates['name'] = value;
          updates['fullName'] = value;
          updates['normalizedName'] = normalizedName;
          updates['fullNameLowercase'] = normalizedName;

          searchData['name'] = value;
          searchData['fullName'] = value;
          searchData['normalizedName'] = normalizedName;
          searchData['fullNameLowercase'] = normalizedName;
        }

        // =====================================================
        // PHONE
        // =====================================================

        if (phone != null) {
          final String value = phone.trim();

          if (value.isEmpty) {
            updates['phone'] = '';
            updates['phoneNumber'] = '';
            updates['phoneNormalized'] = FieldValue.delete();
            updates['phoneDigits'] = FieldValue.delete();
            updates['phoneSearchKeys'] = FieldValue.delete();

            searchData['phone'] = '';
            searchData['phoneNumber'] = '';
            searchData.remove('phoneNormalized');
            searchData.remove('phoneDigits');
            searchData.remove('phoneSearchKeys');
          } else {
            final String normalizedPhone =
            _normalizePhoneForSearch(
              value,
            );

            final List<String> searchKeys =
            _phoneSearchKeys(
              value,
            );

            updates['phone'] = value;
            updates['phoneNumber'] = value;
            updates['phoneNormalized'] = normalizedPhone;
            updates['phoneDigits'] = _digitsOnlyPhone(
              value,
            );
            updates['phoneSearchKeys'] = searchKeys;

            searchData['phone'] = value;
            searchData['phoneNumber'] = value;
            searchData['phoneNormalized'] = normalizedPhone;
            searchData['phoneDigits'] = _digitsOnlyPhone(
              value,
            );
            searchData['phoneSearchKeys'] = searchKeys;
          }
        }

        // =====================================================
        // EMAIL
        // =====================================================

        if (email != null) {
          final String value = email.trim();

          if (value.isEmpty) {
            updates['email'] = FieldValue.delete();
            updates['emailNormalized'] = FieldValue.delete();

            searchData.remove('email');
            searchData.remove('emailNormalized');
          } else {
            _validateEmail(
              value,
            );

            final String normalizedEmail = value.toLowerCase();

            updates['email'] = value;
            updates['emailNormalized'] = normalizedEmail;

            searchData['email'] = value;
            searchData['emailNormalized'] = normalizedEmail;
          }
        }

        // =====================================================
        // PROFILE PHOTO
        // =====================================================

        if (photoUrl != null) {
          _applyMirroredOptionalString(
            updates,
            primaryField: 'photoUrl',
            compatibilityField: 'profilePhotoUrl',
            value: photoUrl,
          );
        }

        // =====================================================
        // COVER PHOTO
        // =====================================================

        if (coverPhoto != null) {
          _applyMirroredOptionalString(
            updates,
            primaryField: 'coverPhoto',
            compatibilityField: 'coverPhotoUrl',
            value: coverPhoto,
          );

          final String normalized = coverPhoto.trim();

          if (normalized.isEmpty) {
            updates['backgroundPhotoUrl'] = FieldValue.delete();
          } else {
            updates['backgroundPhotoUrl'] = normalized;
          }
        }

        // =====================================================
        // BIO
        // =====================================================

        if (bio != null) {
          _applyOptionalString(
            updates,
            field: 'bio',
            value: bio,
          );
        }

        // =====================================================
        // COUNTRY
        // =====================================================

        if (country != null) {
          _applyOptionalString(
            updates,
            field: 'country',
            value: country,
          );
        }

        if (countryCode != null) {
          final String normalized =
          countryCode
              .trim()
              .toUpperCase();

          if (normalized.isEmpty) {
            updates['countryCode'] = FieldValue.delete();
          } else {
            updates['countryCode'] = normalized;
          }
        }

        // =====================================================
        // GENDER
        // =====================================================

        if (gender != null) {
          _applyOptionalString(
            updates,
            field: 'gender',
            value: gender,
          );
        }

        // =====================================================
        // PROVIDER
        // =====================================================

        if (provider != null) {
          _applyOptionalString(
            updates,
            field: 'provider',
            value: provider,
          );
        }

        // =====================================================
        // DEVICE TOKEN
        // =====================================================

        if (deviceToken != null) {
          _applyOptionalString(
            updates,
            field: 'deviceToken',
            value: deviceToken,
          );
        }

        // =====================================================
        // DATE OF BIRTH
        // =====================================================

        if (dateOfBirth != null) {
          updates['dateOfBirth'] = Timestamp.fromDate(
            _dateOnly(
              dateOfBirth,
            ),
          );
        }

        // =====================================================
        // USERNAME
        // =====================================================

        if (username != null) {
          _deleteReservationIfOwned(
            transaction: transaction,
            reference: oldUsernameRef,
            snapshot: oldUsernameSnapshot,
            ownerUid: normalizedUid,
          );

          if (requestedUsername == null) {
            updates['username'] = FieldValue.delete();
            updates['normalizedUsername'] = FieldValue.delete();
            updates['usernameLowercase'] = FieldValue.delete();

            searchData.remove('username');
            searchData.remove('normalizedUsername');
            searchData.remove('usernameLowercase');
          } else {
            updates['username'] = requestedUsername;
            updates['normalizedUsername'] = requestedUsername;
            updates['usernameLowercase'] = requestedUsername;

            searchData['username'] = requestedUsername;
            searchData['normalizedUsername'] = requestedUsername;
            searchData['usernameLowercase'] = requestedUsername;

            transaction.set(
              _usernameReservations.doc(
                requestedUsername,
              ),
              _reservationDocument(
                uid: normalizedUid,
                value: requestedUsername,
                existing: newUsernameSnapshot?.exists ?? false,
              ),
              SetOptions(
                merge: true,
              ),
            );
          }
        }

        // =====================================================
        // JR CALL PUBLIC ADDRESS
        // =====================================================

        if (userAddress != null) {
          _deleteReservationIfOwned(
            transaction: transaction,
            reference: oldAddressRef,
            snapshot: oldAddressSnapshot,
            ownerUid: normalizedUid,
          );

          if (requestedAddress == null) {
            updates['userAddress'] = FieldValue.delete();
            updates['normalizedUserAddress'] = FieldValue.delete();
            updates['jrCallUserId'] = FieldValue.delete();
            updates['jrCallUserIdLowercase'] = FieldValue.delete();

            searchData.remove('userAddress');
            searchData.remove('normalizedUserAddress');
            searchData.remove('jrCallUserId');
            searchData.remove('jrCallUserIdLowercase');
          } else {
            updates['userAddress'] = requestedAddress;
            updates['normalizedUserAddress'] = requestedAddress;
            updates['jrCallUserId'] = requestedAddress;
            updates['jrCallUserIdLowercase'] = requestedAddress;

            searchData['userAddress'] = requestedAddress;
            searchData['normalizedUserAddress'] = requestedAddress;
            searchData['jrCallUserId'] = requestedAddress;
            searchData['jrCallUserIdLowercase'] = requestedAddress;

            transaction.set(
              _userAddressReservations.doc(
                requestedAddress,
              ),
              _reservationDocument(
                uid: normalizedUid,
                value: requestedAddress,
                existing: newAddressSnapshot?.exists ?? false,
              ),
              SetOptions(
                merge: true,
              ),
            );
          }
        }

        // =====================================================
        // GLOBAL DISCOVERY INDEX
        //
        // Rebuilt from the complete final profile state.
        // No stale old name/username/JR ID/email/phone fragments
        // are allowed to survive a profile change.
        // =====================================================

        _applySearchIndexToUpdates(
          uid: normalizedUid,
          searchData: searchData,
          updates: updates,
        );

        transaction.update(
          userRef,
          updates,
        );
      },
    );
  }

